      "        Effect.gen(function* () {",
      "          // The scout is told to change nothing. This is what makes that an enforced rule",
      "          // rather than a sentence in a prompt file: an instruction no code checks is a",
      "          // request, and the whole point of the guard is that a request is not a boundary.",
      "          const scouted = (yield* withPermissions(",
      '            mayNotTouchTheFactory("scout"),',
      "            agent({",
      '              name: "scout",',
      '              description: "Find where the fault lives; change nothing",',
      '              agent: "scout",',
      "              prompt: payload.fault,",
      "              envelope: Scouted,",
      "              checks: scoutedChecks,",
      "            }),",
      "          )).value;",
      "",
      "          // `withPermissions` fingerprints the change-set, runs the phase, and compares. A path",
      "          // outside the policy is undone and the run fails with a `PermissionBreach` naming",
      "          // every path and what became of it \u2014 a breach is not something a re-prompt can fix,",
      "          // because the write already happened.",
      "          const first = (yield* withPermissions(",
      '            mayNotTouchTheFactory("hotfixer"),',
      "            agent({",
      '              name: "fix",',
      '              description: "Write the smallest change that resolves the fault",',
      '              agent: "hotfixer",',
