      "              checks: builtChecks,",
      "            }),",
      "          )).value;",
      "",
      '          yield* commit("fix", first.summary);',
      "",
      "          // A rejected fix goes back to the same agent, in the same conversation, and the run",
      "          // suspends on every asking — container released, branch retained. `limit` bounds it,",
      "          // and spending the bound fails with the last reviewer's own words.",
      "          const approved = yield* reviewed({",
      '            name: "approve",',
      '            description: "Does this fix land?",',
      "            actor,",
      "            limit: 3,",
      "            deadline: Duration.days(2),",
      "            onExpiry: OnExpiry.fail(),",
      "            subject: first,",
      "            // Read again on every asking, so the second reviewer sees the *revised* fix rather",
      "            // than the diff they already rejected.",
      '            context: (fix) => ({ summary: fix.summary, files: fix.changedFiles.join(", ") }),',
      "            revise: (verdict, fix) =>",
